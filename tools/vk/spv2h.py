#!/usr/bin/env python3
"""Turn the Vulkan self-test SPIR-V into a committed C header.

    python3 tools/vk/spv2h.py

The game has no build-time dependency on glslangValidator: the two self-test shaders are
tiny and change approximately never, so their SPIR-V is generated here and committed. Re-run
this after editing tools/vk/selftest.vert/.frag:

    "$VULKAN_SDK/Bin/glslangValidator" -V tools/vk/selftest.vert -o tools/vk/selftest.vert.spv
    "$VULKAN_SDK/Bin/glslangValidator" -V tools/vk/selftest.frag -o tools/vk/selftest.frag.spv
    python3 tools/vk/spv2h.py
"""
import struct, os
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "game", "src", "gfx", "vk_selftest_spv.h")

def words(path):
    d = open(path, "rb").read()
    assert len(d) % 4 == 0, path
    w = struct.unpack("<%dI" % (len(d) // 4), d)
    assert w[0] == 0x07230203, "%s is not SPIR-V (magic %08x)" % (path, w[0])
    return w

def emit(f, name, w):
    f.write("static const unsigned %s[] = {\n" % name)
    for i in range(0, len(w), 6):
        f.write("    " + " ".join("0x%08xu," % x for x in w[i:i + 6]) + "\n")
    f.write("};\n\n")

with open(OUT, "w") as f:
    f.write("// SPIR-V for the Vulkan self test, generated by tools/vk/spv2h.py from\n"
            "// tools/vk/selftest.vert and .frag. Committed so that building the game needs no\n"
            "// shader compiler; re-run the tool if those two shaders change.\n\n"
            "#ifndef MARE_VK_SELFTEST_SPV_H\n#define MARE_VK_SELFTEST_SPV_H\n\n")
    emit(f, "vk_selftest_vert_spv", words(os.path.join(HERE, "selftest.vert.spv")))
    emit(f, "vk_selftest_frag_spv", words(os.path.join(HERE, "selftest.frag.spv")))
    f.write("#endif\n")
print("wrote", os.path.normpath(OUT))
